// Writes docs/native-review.md: every DE and FR copy block a native speaker should check.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const skip = /(^|\.)(_review|src|relatedCase|date|year)$/;
const leaves = (v, pre = '') => Array.isArray(v) ? v.flatMap((x, i) => leaves(x, `${pre}[${i}]`)) : v && typeof v === 'object' ? Object.entries(v).flatMap(([k, x]) => leaves(x, pre ? `${pre}.${k}` : k)) : typeof v === 'string' && v && !skip.test(pre) ? [[pre, v]] : [];
let out = '# Native review list\n\nGenerated by `npm run review-list`. Every block below is a first draft and needs a native check. Priority: home, agencies, ki-check, then the rest.\n';
for (const l of ['de', 'fr']) {
  const files = walk(`src/content/${l}`).sort();
  out += `\n## ${l.toUpperCase()} (${files.length} files)\n`;
  for (const f of files) {
    const items = leaves(JSON.parse(readFileSync(f, 'utf8')));
    out += `\n### ${f.replace('src/content/', '')} (${items.length} blocks)\n\n` + items.map(([k, v]) => `- [ ] \`${k}\`: ${v}`).join('\n') + '\n';
  }
}
writeFileSync(join('docs', 'native-review.md'), out);
console.log('docs/native-review.md written');
